void *memcpy(void *restrict dest, const void *restrict src, size_t n) {
    uint8_t *restrict pdest = (uint8_t *restrict)dest;
    const uint8_t *restrict psrc = (const uint8_t *restrict)src;

    for (size_t i = 0; i < n; i++) {
        pdest[i] = psrc[i];
    }

    return dest;
}

void *memset(void *s, int c, size_t n) {
    uint8_t *p = (uint8_t *)s;

    for (size_t i = 0; i < n; i++) {
        p[i] = (uint8_t)c;
    }

    return s;
}

void *memmove(void *dest, const void *src, size_t n) {
    uint8_t *pdest = (uint8_t *)dest;
    const uint8_t *psrc = (const uint8_t *)src;

    if (src > dest) {
        for (size_t i = 0; i < n; i++) {
            pdest[i] = psrc[i];
        }
    } else if (src < dest) {
        for (size_t i = n; i > 0; i--) {
            pdest[i-1] = psrc[i-1];
        }
    }

    return dest;
}

int memcmp(const void *s1, const void *s2, size_t n) {
    const uint8_t *p1 = (const uint8_t *)s1;
    const uint8_t *p2 = (const uint8_t *)s2;

    for (size_t i = 0; i < n; i++) {
        if (p1[i] != p2[i]) {
            return p1[i] < p2[i] ? -1 : 1;
        }
    }

    return 0;
}

// Halt and catch fire function.
static void hcf(void) {
    for (;;) {
        asm ("hlt");
    }
}

// The following will be our kernel's entry point.
// If renaming kmain() to something else, make sure to change the
// linker script accordingly.
void kmain(void) {
    // Ensure the bootloader actually understands our base revision (see spec).
    if (LIMINE_BASE_REVISION_SUPPORTED == false) {
        hcf();
    }
    // Ensure we got a framebuffer.
    if (framebuffer_request.response == NULL
     || framebuffer_request.response->framebuffer_count < 1) {
        hcf();
    }
    // Fetch the first framebuffer.
    struct limine_framebuffer *framebuffer = framebuffer_request.response->framebuffers[0];
    // Note: we assume the framebuffer model is RGB with 32-bit pixels.
    /*for (size_t i = 0; i < 100; i++) { // * Draw a line
        volatile uint32_t *fb_ptr = framebuffer->address;
        fb_ptr[i * (framebuffer->pitch / 4) + i] = 0xffffff;
    }*/ 
    // Print a string
    print_string(framebuffer, "\nHello world!", 0xff0000); // White text
    bool red = false;
    for (int i = 0; i < sizeof(font) / sizeof(font[0]); ++i) {
        if (red)
        {
            print_char(framebuffer, i, 0xff0000);
        }
        else print_char(framebuffer, i, 0xffffff);
        red = !red;
    }
    print_char(framebuffer, 10, 0xffffff); // Try printing 'A' in white
    // We're done, just hang...
    hcf();
}


static volatile size_t cursor_x = 0;
static volatile size_t cursor_y = 0;

void putpixel(struct limine_framebuffer *fb, size_t x, size_t y, uint32_t color) {
    if (x < fb->width && y < fb->height) {
        uint32_t *pixel_ptr = fb->address;
        pixel_ptr[y * (fb->pitch / 4) + x] = color;
    }
}

void print_char(struct limine_framebuffer *fb, char c, uint32_t color) {
    if (fb == NULL) {
        return;
    }

    if (c == '\n') {
        cursor_x = 0;
        cursor_y += FONT_HEIGHT;
        return;
    }

    /*if (c < 32 || c > 126) { // Handle unprintable characters (e.g., as a space)
        c = ' ';
    }*/

    for (size_t y = 0; y < FONT_HEIGHT; y++) {
        unsigned char row = font[(int)c][y];
        for (size_t x = 0; x < FONT_WIDTH; x++) {
            if ((row >> x) & 1) {
                putpixel(fb, cursor_x + x, cursor_y + y, color);
            }
        }
    }

    cursor_x += FONT_WIDTH;
    if (cursor_x >= fb->width - FONT_WIDTH) {
        cursor_x = 0;
        cursor_y += FONT_HEIGHT;
    }
}

void print_string(struct limine_framebuffer *fb, const char *str, uint32_t color) {
    while (*str) {
        print_char(fb, *str++, color);
    }
}
